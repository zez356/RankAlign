def class_texts(dataset: str) -> list[list[str]]:
    if dataset == "cifar100":
        names = CIFAR100_CLASSES
        defs = [f"{n} - {CIFAR100_DEFINITIONS[n]}" for n in names]
        desc = CIFAR_DESC
    elif dataset == "imagenet100":
        names = IMAGENET100_CLASSES
        defs = IMAGENET100_DEFINITIONS
        desc = IN100_DESC
    else:
        raise ValueError(f"unknown dataset {dataset!r}")
    texts = [[d] + list(desc[n]) for n, d in zip(names, defs)]
    assert len(texts) == 100 and all(len(t) == 4 for t in texts)
    return texts


